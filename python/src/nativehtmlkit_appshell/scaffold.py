"""Create a complete independently installable extension without importing AppShell at runtime."""
from __future__ import annotations

from pathlib import Path
import json
import re

from .contract import EXTENSION_ID


class ScaffoldError(ValueError):
    pass


def _validate(ident: str, destination: Path) -> None:
    if len(ident) > 140 or not EXTENSION_ID.fullmatch(ident):
        raise ScaffoldError("--id must be a lowercase reverse-domain ID, e.g. org.example.hello")
    if destination.exists():
        raise ScaffoldError(f"Destination already exists: {destination}")


def generate_python(ident: str, destination: Path, *, title: str | None = None) -> Path:
    destination = destination.expanduser().absolute()
    _validate(ident, destination)
    mod = "appshell_" + re.sub("[^a-z0-9_]", "_", ident)
    dist = "appshell-ext-" + ident.replace(".", "-")
    title = (title or ident.rsplit(".", 1)[-1].replace("-", " ").title()).strip()
    if not title or len(title) > 120 or any(ord(c) < 32 for c in title):
        raise ScaffoldError("--title must be 1-120 printable characters")
    destination.mkdir(parents=True)
    (destination / "src" / mod).mkdir(parents=True)
    (destination / "tests").mkdir()
    (destination / "pyproject.toml").write_text(f'''[build-system]
requires = ["setuptools>=75"]
build-backend = "setuptools.build_meta"

[project]
name = "{dist}"
version = "0.1.0"
description = {json.dumps(title + " extension for NativeHTMLKit AppShell", ensure_ascii=False)}
requires-python = ">=3.10"

[project.entry-points."nativehtmlkit.appshell.extensions"]
"{ident}" = "{mod}:Extension"

[tool.setuptools.packages.find]
where = ["src"]
''', encoding="utf-8")
    (destination / "src" / mod / "__init__.py").write_text(f'''"""A normal Python extension: no dependency on NativeHTMLKit or AppShell."""
from pathlib import Path


class Extension:
    def manifest(self, context):
        return {{
            "api_version": 1,
            "id": "{ident}",
            "title": {title!r},
            "version": "0.1.0",
            "pages": [{{"id": "overview", "title": "Overview", "order": 10}}],
            "commands": [
                {{"id": "refresh", "title": "Refresh", "risk": "read"}},
                {{"id": "save", "title": "Save text", "risk": "write",
                  "confirmation": "Save this text into this extension's private data directory?"}},
            ],
        }}

    def page(self, page_id, context):
        if page_id != "overview":
            raise ValueError("Unknown page")
        saved = Path(context["data_dir"]) / "message.txt"
        message = saved.read_text(encoding="utf-8") if saved.is_file() else "Hello from Python."
        return {{"title": {title!r}, "blocks": [
            {{"kind": "heading", "text": {title!r}, "level": 2}},
            {{"kind": "text", "text": "This page is generated by a Python package."}},
            {{"kind": "input", "name": "message", "label": "Message", "value": message}},
            {{"kind": "row", "children": [
                {{"kind": "button", "text": "Refresh", "command": "refresh"}},
                {{"kind": "button", "text": "Save", "command": "save"}},
            ]}},
        ]}}

    def action(self, command_id, values, params, context):
        if command_id == "refresh":
            return {{"message": "Page refreshed", "refresh": True}}
        if command_id == "save":
            path = Path(context["data_dir"]) / "message.txt"
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(str(values.get("message", ""))[:10000], encoding="utf-8")
            return {{"message": "Message saved", "refresh": True}}
        raise ValueError("Unknown command")

    def shutdown(self, context):
        pass
''', encoding="utf-8")
    (destination / "tests" / "test_extension.py").write_text(f'''from {mod} import Extension


def test_contract():
    plugin = Extension()
    context = {{"data_dir": "/tmp", "extension_id": "{ident}", "app_version": "0.1.0"}}
    assert plugin.manifest(context)["api_version"] == 1
    assert plugin.page("overview", context)["title"] == {title!r}
    assert plugin.action("refresh", {{}}, {{}}, context)["refresh"] is True
''', encoding="utf-8")
    (destination / "README.md").write_text(f'''# {title} — AppShell Python extension

Install it by copying this directory under AppShell's `extensions/` folder, or run
`appshell stage add .` from the project directory and restart AppShell.

The extension uses plain dictionaries and a Python entry point. It never imports
AppShell, NativeHTMLKit, or PowerShell. `manifest` must be read-only and fast; `page`
returns validated semantic blocks; `action` is invoked after shell confirmation.
Update `pyproject.toml` and `manifest()` versions together. See root `contracts/`.
''', encoding="utf-8")
    return destination
